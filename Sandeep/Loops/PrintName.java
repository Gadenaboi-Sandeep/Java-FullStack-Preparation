public class PrintName {
    public static void main(String[] args) {
        int n=5;
        int temp=5;
        for(int i=1;i<=5;i++){
            System.out.println(i+" For: Sandeep ");
        }
        while(n>0){
            System.out.println(n+" While: Sandeep ");
            n--;
        }
        do{
            System.out.println(temp+" Do While: Sandeep ");
            temp--;
        }while(temp>0);
    }
}
