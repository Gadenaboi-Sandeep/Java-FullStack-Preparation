package Chinna.Day3;

public class SequenceNumbers {
    public static void main(String args[]){
        // From 100 to 1
        for(int i=100; i>=1 ;i--){
            System.out.println(i);
        }
       // From 1 to 100 
        for(int i=1;i<=100;i++){
            System.out.println(i);
        }
    }
}
